# =============================================================================
#  Forward_Dosimetry_Stochastic.r
#  Stochastic (population) counterpart to shiny_app/R/forward_dosimetry.r.
#
#  forward_dosimetry_stochastic() below takes the SAME dosing/exposure
#  arguments, but replaces the single fixed BW with a popgen virtual
#  population -- the same population-generation inputs
#  Extended_Model_Population.r's .generate_population() requires (n,
#  dataset, age_range, bmi_range, height_range, prob_male, ethnicity_probs,
#  population_type, optional seed). Physiology (organ mass/flow,
#  sex-specific hematocrit, age-corrected GFR) comes from
#  Extended_Model_Population.r exactly as its own .run_population_extended()
#  already produces it; the one thing that function does NOT do --
#  converting a per-kg-BW ingestion rate to an absolute amount using BW
#  (forward_dosimetry()'s `ingestion * BW / 1000`, done once there because
#  there is only one BW) -- is done per individual here instead, since every
#  virtual individual has a different popgen-derived body weight.
#
#  Dosing note: Extended_Model_Population.r's .create.events() no longer has
#  a separate admin_type ("bolus"/"oral") switch -- dosing is driven purely
#  by `exp_type`: "pharmacokinetics" adds `ingestion` (dose amount(s)) to the
#  stomach lumen at `ingestion_time`; "continuous" treats `ingestion` as a
#  repeating intake RATE instead. There is no more admin_dose/admin_time/
#  admin_type at all -- every dose, one-off or continuous, goes through
#  `ingestion`/`ingestion_time`, and .ingestion_for_BW() below BW-scales it
#  per individual either way.
#
#  Dependencies: Extended_Model_Population.r (and, transitively,
#  popgen_consts.R / popgen_port.R, estimated_parameters.csv) must be in the
#  working directory.
# =============================================================================

library(deSolve)
library(tidyverse)

